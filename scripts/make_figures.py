def fig08(master):
    df = master[(master["experiment"] == "expA_fd_verification")
                & (master["policy_iteration"] >= 0)]
    if len(df) == 0:
        skipped.append("fig08 (no expA iteration rows)")
        return
    piv = df.pivot_table(index=["method", "method_seed",
                                "policy_iteration"],
                         columns="metric", values="value",
                         aggfunc="first").reset_index()
    T = 24.0
    piv["bound_expr"] = T * (piv.get("val_max_residual", np.nan)
                             + piv.get("hjb_max_residual", np.nan))
    piv = piv[np.isfinite(piv["bound_expr"])
              & np.isfinite(piv.get("cost_gap_eJ", np.nan))]
    if len(piv) == 0:
        skipped.append("fig08 (no joint rows)")
        return
    piv["eJ_pos"] = piv["cost_gap_eJ"].clip(lower=1e-10)
    fig, axes = plt.subplots(1, 3, figsize=(7.2, 2.6))
    ax = axes[0]
    for m, sub in piv.groupby("method"):
        st = sty(m)
        ax.scatter(sub["eJ_pos"], sub["bound_expr"], s=14,
                   color=st["color"], marker=st["marker"] or "o",
                   label=st["label"], alpha=0.8)
    lims = [min(piv["eJ_pos"].min(), piv["bound_expr"].min()) * 0.5,
            max(piv["eJ_pos"].max(), piv["bound_expr"].max()) * 2]
    ax.plot(lims, lims, "k--", lw=0.8, label="$y=x$")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("realized gap $e_J$ (currency)")
    ax.set_ylabel("$T(\\widehat R^{\\pi}_\\infty+\\widehat R^{*}_\\infty)$"
                  "\n(empirical estimate)", fontsize=7.5)
    panel_label(ax, "a")
    ax.legend()
    ax = axes[1]
    eff = piv["bound_expr"] / piv["eJ_pos"]
    ax.hist(np.log10(eff), bins=25, color="#D55E00", alpha=0.75)
    ax.set_xlabel("log10 effectivity index")
    ax.set_ylabel("count")
    panel_label(ax, "b")
    ax = axes[2]
    from scipy.stats import spearmanr
    metrics = [("train_rms_residual", "train RMS"),
               ("val_max_residual", "val max"),
               ("bound_expr", "bound expr")]
    vals, names = [], []
    for col, nm in metrics:
        if col in piv.columns:
            ok = np.isfinite(piv[col])
            r, _ = spearmanr(piv.loc[ok, col], piv.loc[ok, "eJ_pos"])
            vals.append(r)
            names.append(nm)
    ax.barh(names, vals, color=["#999999", "#0072B2", "#D55E00"][:len(vals)])
    ax.set_xlabel("Spearman corr. with $e_J$")
    ax.set_xlim(-1, 1)
    ax.axvline(0, color="k", lw=0.8)
    panel_label(ax, "c")
    save_figure(fig, "fig08_residual_certificate_effectivity", piv)


