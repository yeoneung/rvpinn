def fig03():
    path = os.path.join(RAW, "expA", "fig3_surfaces.npz")
    if not os.path.exists(path):
        skipped.append("fig03 (no expA surfaces)")
        return
    d = np.load(path)
    s, y = d["s"], d["y"]
    panels = [("V_fd", "FD value", "V"), ("V_direct_hjb", "Direct HJB-PINN value", "V"),
              ("V_rvpinnpi", "RV-PINN-PI value", "V"),
              ("A_fd", "FD policy", "A"), ("A_direct_hjb", "Direct HJB-PINN policy", "A"),
              ("A_rvpinnpi", "RV-PINN-PI policy", "A")]
    vmin_v = min(d[k].min() for k, _, tp in panels if tp == "V" and k in d)
    vmax_v = max(d[k].max() for k, _, tp in panels if tp == "V" and k in d)
    vmax_a = max(abs(d[k]).max() for k, _, tp in panels if tp == "A" and k in d)
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 4.6), sharex=True,
                             sharey=True)
    letters = "abcdef"
    for i, (key, title, tp) in enumerate(panels):
        ax = axes[i // 3, i % 3]
        if key not in d:
            ax.axis("off")
            continue
        if tp == "V":
            # explicit shared level array => genuinely common color scale
            lv = np.linspace(vmin_v, vmax_v, 21)
            im = ax.contourf(y, s, np.clip(d[key], vmin_v, vmax_v),
                             levels=lv, cmap="viridis")
        else:
            lv = np.linspace(-vmax_a, vmax_a, 21)
            im = ax.contourf(y, s, np.clip(d[key], -vmax_a, vmax_a),
                             levels=lv, cmap="RdBu_r")
        ax.set_title(title)
        panel_label(ax, letters[i])
        if i % 3 == 0:
            ax.set_ylabel("SoC $s$")
        if i // 3 == 1:
            ax.set_xlabel("$y$ (kW)")
        # colorbar label only on the last column, so it cannot be read as
        # the y-label of the neighbouring panel (third revision)
        fig.colorbar(im, ax=ax, shrink=0.85,
                     label=("currency" if tp == "V" else "kW")
                     if i % 3 == 2 else None)
    df = pd.DataFrame({"s": np.repeat(s, len(y)),
                       "y": np.tile(y, len(s)),
                       **{k: d[k].ravel() for k, _, _ in panels if k in d}})
    save_figure(fig, "fig03_fd_verification_value_policy", df)


def fig04(master):
    df = master[(master["experiment"] == "expA_fd_verification")
                & (master["policy_iteration"] >= 0)
                & (master["method"] == "rvpinnpi")]
    if len(df) == 0:
        skipped.append("fig04 (no per-iteration expA rows)")
        return
    piv = df.pivot_table(index=["method_seed", "policy_iteration"],
                         columns="metric", values="value", aggfunc="first"
                         ).reset_index()
    fig, axes = plt.subplots(2, 2, figsize=(7.2, 5.0))
    specs = [("train_rms_residual", "Training RMS residual (currency/h)",
              True), ("val_max_residual",
                      "Validation max residual", True),
             ("cost_gap_eJ", "Realized FD policy gap $e_J$ (currency)",
              True), ("rollout_cost", "Estimated policy cost (CRN rollouts)",
                      False)]
    letters = "abcd"
    for i, (metric, ylabel, logy) in enumerate(specs):
        ax = axes[i // 2, i % 2]
        if metric not in piv.columns:
            ax.axis("off")
            continue
        for seed, sub in piv.groupby("method_seed"):
            sub = sub.sort_values("policy_iteration")
            vals = sub[metric]
            if logy:
                vals = vals.clip(lower=1e-12)
            ax.plot(sub["policy_iteration"], vals, color="#D55E00",
                    alpha=0.25, lw=0.8)
        med = piv.groupby("policy_iteration")[metric].median()
        q1 = piv.groupby("policy_iteration")[metric].quantile(0.25)
        q3 = piv.groupby("policy_iteration")[metric].quantile(0.75)
        if logy:
            med, q1, q3 = (v.clip(lower=1e-12) for v in (med, q1, q3))
        ax.plot(med.index, med.values, color="#D55E00", lw=1.8,
                marker="o", label="median")
        ax.fill_between(med.index, q1.values, q3.values, color="#D55E00",
                        alpha=0.2, label="IQR")
        if logy:
            ax.set_yscale("log")
        ax.set_xlabel("Policy iteration $n$")
        ax.set_ylabel(ylabel, fontsize=7.5)
        panel_label(ax, letters[i])
        if i == 0:
            ax.legend()
    save_figure(fig, "fig04_pi_convergence_residual_gap", piv)


