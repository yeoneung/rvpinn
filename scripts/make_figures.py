    axes[0].hist(s_next, bins=100, color="#0072B2", alpha=0.8)
    axes[0].axvline(p.s_min, color="k", ls=":")
    axes[0].axvline(p.s_max, color="k", ls=":")
    axes[0].set_xlabel("next-step SoC after projection (1M random pairs)")
    axes[0].set_ylabel("count")
    panel_label(axes[0], "a")
    axes[1].scatter(s[:5000], a[:5000], s=1, alpha=0.3, color="#D55E00")
    axes[1].set_xlabel("SoC $s$")
    axes[1].set_ylabel("projected action (kW)")
    panel_label(axes[1], "b")
    viol = int(((s_next < p.s_min - 1e-12)
                | (s_next > p.s_max + 1e-12)).sum())
    save_figure(fig, "figS04_soc_safety_stress_test",
                {"n_samples": n, "violations": viol, "seed": 20260731})


