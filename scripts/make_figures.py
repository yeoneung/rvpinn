def fig02():
    # Second revision (Reviewer 1, Comment 1): every arrow is a straight or
    # orthogonal (elbow) polyline, and each label is centred on a segment of
    # its own arrow with one uniform clearance (GAP), so no label can be read
    # as belonging to a neighbouring arrow. The policy loop is routed above
    # the top row and the stopping-test arrow enters the policy-evaluation
    # block through its own elbow (no crossings). Box contents unchanged.
    fig, ax = plt.subplots(figsize=(7.2, 3.9))
    ax.axis("off")
    LW, COL, GAP, FS = 1.2, "#333333", 0.022, 7

    def box(x, y, w, h, text, fc="#EEF3FA", ec="#4477AA"):
        ax.add_patch(plt.Rectangle((x, y), w, h, fc=fc, ec=ec, lw=1.2,
                                   zorder=2))
        ax.text(x + w / 2, y + h / 2, text, ha="center", va="center",
                fontsize=8, zorder=3)

    def arrow(pts, text="", seg=0, side=+1, color=COL):
        """Polyline arrow through pts (arrowhead on the last segment). A
        label is centred on segment `seg` and offset by GAP perpendicular
        to it (side=+1: above a horizontal / right of a vertical segment)."""
        xs, ys = zip(*pts)
        if len(pts) > 2:
            ax.plot(xs[:-1], ys[:-1], color=color, lw=LW,
                    solid_joinstyle="miter", zorder=1)
        ax.annotate("", xy=pts[-1], xytext=pts[-2],
                    arrowprops=dict(arrowstyle="-|>", color=color, lw=LW,
                                    shrinkA=0, shrinkB=0))
        if text:
            (x0, y0), (x1, y1) = pts[seg], pts[seg + 1]
            xm, ym = (x0 + x1) / 2, (y0 + y1) / 2
            if abs(y1 - y0) < 1e-9:          # horizontal segment
                ax.text(xm, ym + side * GAP, text, ha="center",
                        va="bottom" if side > 0 else "top",
                        fontsize=FS, color=color, zorder=4)
            else:                            # vertical segment
                ax.text(xm + side * GAP, ym, text,
                        ha="left" if side > 0 else "right", va="center",
                        fontsize=FS, color=color, zorder=4)

    # top row: the policy-iteration loop; bottom row: the disjoint point sets
    box(0.02, 0.62, 0.20, 0.26, "Policy evaluation\nPINN solves linear\n"
        "$\\partial_t v+\\mathcal{L}^{\\pi_n}v+\\ell^{\\pi_n}=0$\n"
        "(hard terminal)", fc="#E3F2FD", ec="#0072B2")
    box(0.28, 0.62, 0.20, 0.26, "Residual-adaptive\nrefinement\n"
        "(candidate pool,\ntop quantile)", fc="#FFF3E0", ec="#E69F00")
    box(0.54, 0.62, 0.20, 0.26, "Policy improvement\nscalar Hamiltonian\n"
        "$\\min_{a\\in\\mathcal{A}(s)}$, piecewise\nexact solver",
        fc="#FFF8E1", ec="#D55E00")
    box(0.80, 0.62, 0.18, 0.26, "Safety projection\n"
        "$\\mathcal{A}(s)\\cap\\mathcal{A}_\\Delta(s)$\n(deployment)",
        fc="#E8F5E9", ec="#009E73")
    box(0.02, 0.06, 0.20, 0.30, "Training points\nfresh Sobol\n(+ adaptive "
        "buffer)\nseed 2101/2201", fc="#F5F5F5", ec="#999999")
    box(0.28, 0.06, 0.20, 0.30, "Tuning-validation\nfrozen Sobol\nseed 3101\n"
        "early stop + selection", fc="#F5F5F5", ec="#999999")
    box(0.54, 0.06, 0.20, 0.30, "Residual-audit design\nfrozen Sobol seed "
        "4101\nNEVER used in training\nevaluated once after freeze",
        fc="#FDECEA", ec="#D55E00")
    box(0.80, 0.06, 0.18, 0.30, "Residual expression\n$2e_T+T(R^{\\pi}+R^{*})$\n"
        "+ Lipschitz-corrected\nsensitivity estimate",
        fc="#FDECEA", ec="#882255")

    # forward chain along the top row
    arrow([(0.22, 0.75), (0.28, 0.75)])
    arrow([(0.48, 0.75), (0.54, 0.75)])
    arrow([(0.74, 0.75), (0.80, 0.75)])
    # policy loop: improvement -> evaluation, routed above the top row;
    # label centred above the horizontal segment of this arrow only
    arrow([(0.64, 0.88), (0.64, 0.97), (0.12, 0.97), (0.12, 0.88)],
          "$\\pi_{n+1}$ (loop)", seg=1, side=+1)
    # point sets feeding the loop
    arrow([(0.08, 0.36), (0.08, 0.62)])                    # training points
    arrow([(0.38, 0.36), (0.38, 0.50), (0.17, 0.50), (0.17, 0.62)],
          "stopping test", seg=1, side=+1)                 # tuning-validation
    arrow([(0.64, 0.36), (0.64, 0.50), (0.89, 0.50), (0.89, 0.62)])
    arrow([(0.74, 0.21), (0.80, 0.21)])
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.06)
