def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-new-results", action="store_true")
    ap.add_argument("--only", default=None)
    args = ap.parse_args()
    set_style()
    master = load_master(args.allow_new_results)
    figs = {
        "fig01": fig01, "fig02": fig02, "fig03": fig03,
        "fig04": lambda: fig04(master), "fig05": fig05,
        "fig06": lambda: fig06(master), "fig07": lambda: fig07(master),
        "fig08": lambda: fig08(master),
        "figS01": figS01, "figS02": figS02,
        "figS03": lambda: figS03(master), "figS04": figS04,
        "figS05": lambda: figS05(master), "figS06": lambda: figS06(master),
        "figS07": lambda: figS07(master), "figS08": lambda: figS08(master),
    }
    only = set(args.only.split(",")) if args.only else None
    for name, fn in figs.items():
        if only and name not in only:
            continue
        try:
            fn()
        except Exception as e:
            skipped.append(f"{name} (ERROR: {e})")
            print(f"  {name} FAILED: {e}")
    problems = qa_check()
    report = {"skipped": skipped, "qa_problems": problems}
    with open(os.path.join(ROOT, "paper", "figures", "_figure_qa.json"),
              "w") as f:
        json.dump(report, f, indent=2)
    print("figure QA:", report)
    return 0


